import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, 'public', 'env-config.js')

// Lowest to highest precedence; the shell environment always wins.
const ENV_FILES = [
  '.env',
  '.env.development',
  '.env.production',
  '.env.local',
  '.env.development.local',
  '.env.production.local',
]
const KEYS = ['NEXT_PUBLIC_API_URL', 'API_URL']

function parseEnvFile(path) {
  const values = {}
  if (!existsSync(path)) return values

  for (const rawLine of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim()
    if (!line || line.startsWith('#')) continue

    const separator = line.indexOf('=')
    if (separator === -1) continue

    const key = line.slice(0, separator).trim()
    let value = line.slice(separator + 1).trim()
    if (/^(['"]).*\1$/s.test(value)) value = value.slice(1, -1)

    values[key] = value
  }

  return values
}

function resolveApiUrl() {
  const fromFiles = {}
  for (const file of ENV_FILES) Object.assign(fromFiles, parseEnvFile(join(root, file)))

  for (const key of KEYS) {
    const value = process.env[key] ?? fromFiles[key]
    if (value && value.trim()) return value.trim().replace(/\/+$/, '')
  }

  return ''
}

const apiUrl = resolveApiUrl()

writeFileSync(
  target,
  [
    '/* Generated by scripts/generate-env-config.mjs - do not edit in source.',
    '   Safe to edit in a deployed build to repoint the frontend without rebuilding. */',
    `window.__ENV__ = { API_URL: ${JSON.stringify(apiUrl)} };`,
    '',
  ].join('\n'),
  'utf8',
)

console.log(apiUrl ? `env-config.js -> API_URL=${apiUrl}` : 'env-config.js -> API_URL empty (field stays manually editable)')
